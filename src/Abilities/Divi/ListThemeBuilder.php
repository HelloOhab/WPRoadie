<?php
/**
 * Lists Divi Theme Builder templates and the header, body and footer
 * layouts they use, so the AI can find where the site header lives.
 *
 * @package WPRoadie
 */

namespace WPRoadie\Abilities\Divi;

use WP_Query;
use WPRoadie\Safety\Mode;

defined( 'ABSPATH' ) || exit;

final class ListThemeBuilder extends DiviAbility {

	const AREAS = array( 'header', 'body', 'footer' );

	public function slug(): string {
		return 'divi-list-theme-builder';
	}

	public function label(): string {
		return __( 'List Divi Theme Builder templates', 'wproadie' );
	}

	public function description(): string {
		return __( 'Shows the live Divi Theme Builder: each template (title, default, enabled, use_on and exclude_from conditions such as "singular:post_type:page:all" or "homepage") and its header, body and footer: layout_id (0 = the theme\'s own header/footer, or the default template\'s), enabled (false = hidden on those pages), title, format and modules. The site-wide header and footer are usually on the default template. Edit a layout with divi-get-page / divi-update-module using its layout_id. Read-only: assigning layouts or changing conditions is done in Divi > Theme Builder.', 'wproadie' );
	}

	public function risk(): string {
		return Mode::RISK_READ;
	}

	protected function execute( array $input ) {
		unset( $input );
		$builder = new WP_Query(
			array(
				'post_type'              => 'et_theme_builder',
				'post_status'            => 'publish',
				'posts_per_page'         => 1,
				'orderby'                => 'date',
				'order'                  => 'DESC',
				'fields'                 => 'ids',
				'no_found_rows'          => true,
				'update_post_term_cache' => false,
				// Library copies of a theme builder are not the live one.
				'meta_query'             => array( // phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_query -- One post.
					array(
						'key'     => '_et_library_theme_builder',
						'compare' => 'NOT EXISTS',
					),
				),
			)
		);
		if ( ! $builder->posts ) {
			return array(
				'templates' => array(),
				'note'      => __( 'The Theme Builder has no saved templates: the site uses the theme\'s own header and footer (Divi > Theme Options).', 'wproadie' ),
			);
		}
		$builder_id = (int) $builder->posts[0];

		$templates = array();
		foreach ( array_unique( array_map( 'intval', (array) get_post_meta( $builder_id, '_et_template', false ) ) ) as $template_id ) {
			$template = get_post( $template_id );
			if ( ! $template || 'et_template' !== $template->post_type || 'publish' !== $template->post_status ) {
				continue;
			}
			$item = array(
				'id'           => $template_id,
				'title'        => '1' === get_post_meta( $template_id, '_et_autogenerated_title', true ) ? '' : $template->post_title,
				'default'      => '1' === get_post_meta( $template_id, '_et_default', true ),
				'enabled'      => '1' === get_post_meta( $template_id, '_et_enabled', true ),
				'use_on'       => array_values( array_map( 'strval', (array) get_post_meta( $template_id, '_et_use_on', false ) ) ),
				'exclude_from' => array_values( array_map( 'strval', (array) get_post_meta( $template_id, '_et_exclude_from', false ) ) ),
			);
			foreach ( self::AREAS as $area ) {
				$item[ $area ] = $this->area( $template_id, $area );
			}
			$templates[] = $item;
		}

		usort(
			$templates,
			static function ( $a, $b ) {
				return (int) $b['default'] <=> (int) $a['default'];
			}
		);
		return array(
			'theme_builder_id' => $builder_id,
			'templates'        => $templates,
		);
	}

	/**
	 * One header, body or footer slot of a template.
	 */
	private function area( int $template_id, string $area ): array {
		$layout_id = (int) get_post_meta( $template_id, '_et_' . $area . '_layout_id', true );
		$enabled   = get_post_meta( $template_id, '_et_' . $area . '_layout_enabled', true );
		$slot      = array(
			'layout_id' => $layout_id,
			// Divi saves "1" or "0"; it reads anything else as off.
			'enabled'   => '1' === $enabled,
		);
		if ( '1' === get_post_meta( $template_id, '_et_' . $area . '_layout_global', true ) ) {
			$slot['global'] = true;
		}
		if ( $layout_id ) {
			$layout = get_post( $layout_id );
			if ( $layout ) {
				$slot['title']  = $layout->post_title;
				$slot['format'] = Divi::format_of( $layout );
				if ( $slot['format'] && current_user_can( 'edit_post', $layout_id ) && strlen( $layout->post_content ) <= Divi::MAX_CONTENT ) {
					$slot['modules'] = ( new Document( (string) $layout->post_content, $slot['format'] ) )->module_count();
				}
			} else {
				$slot['missing'] = true;
			}
		}
		return $slot;
	}
}
